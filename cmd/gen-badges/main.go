// gen-badges emits the badge code -> description map as a TypeScript constant
// for the frontend to compile into its bundle.
//
// Badge definitions are effectively static: the badges table is seeded by
// migration and only ever grows, one row at a time, via the admin-only
// ConfigService.AddBadge RPC. Shipping the map in the bundle removes roughly
// 30M requests/month to ProfileService.GetBadgesMetadata, which was 33% of all
// API traffic because DisplayUserBadges mounts one query observer per rendered
// username.
//
// Badge images are already bundled (see badge.tsx, which dynamically imports
// ../assets/badges/<code>.png), so adding a badge already requires a frontend
// deploy. Adding a badge is therefore three steps that happen together:
//
//	1. call ConfigService.AddBadge
//	2. commit the PNG to liwords-ui/src/assets/badges/
//	3. re-run this generator and commit the result
//
// Requires the same DB env vars as liwords-api: DB_CONN_DSN.
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/rs/zerolog"
	"github.com/rs/zerolog/log"

	"github.com/woogles-io/liwords/pkg/config"
	"github.com/woogles-io/liwords/pkg/stores/models"
)

const defaultOut = "liwords-ui/src/gen/badges.ts"

const header = `// Code generated by cmd/gen-badges. DO NOT EDIT.
//
// Badge code -> description, baked in at build time so the frontend never has
// to call ProfileService.GetBadgesMetadata on the hot path.
// Regenerate with: go run ./cmd/gen-badges

`

func main() {
	out := flag.String("out", defaultOut, "Output path for the generated TypeScript file")
	flag.Parse()

	zerolog.TimeFieldFormat = zerolog.TimeFormatUnix
	log.Logger = log.Output(zerolog.ConsoleWriter{Out: os.Stderr})
	zerolog.SetGlobalLevel(zerolog.InfoLevel)

	ctx := context.Background()

	cfg := &config.Config{}
	cfg.Load(nil)

	pool, err := pgxpool.New(ctx, cfg.DBConnUri)
	if err != nil {
		log.Fatal().Err(err).Msg("db-connect-failed")
	}
	defer pool.Close()

	rows, err := models.New(pool).GetBadgesMetadata(ctx)
	if err != nil {
		log.Fatal().Err(err).Msg("query-failed")
	}
	if len(rows) == 0 {
		log.Fatal().Msg("no badges found; refusing to write an empty map")
	}

	// Sort by code so regenerating produces a stable diff.
	sort.Slice(rows, func(i, j int) bool { return rows[i].Code < rows[j].Code })

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("export const BADGE_DESCRIPTIONS: Record<string, string> = {\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "  %s: %s,\n", tsString(r.Code), tsString(r.Description))
	}
	b.WriteString("};\n")

	if err := os.WriteFile(*out, []byte(b.String()), 0644); err != nil {
		log.Fatal().Err(err).Str("out", *out).Msg("write-failed")
	}
	log.Info().Int("badges", len(rows)).Str("out", *out).Msg("wrote-badges")
}

// tsString renders s as a double-quoted TypeScript string literal.
func tsString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
