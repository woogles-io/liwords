type rateCase struct {
	r, rd, vol, ro, rdo float64
	spread, secs        int
	want                [3]float64
}

func checkCases(t *testing.T, p Params, cases []rateCase, tol float64) {
	t.Helper()
	for i, c := range cases {
		r, rd, vol := p.Rate(c.r, c.rd, c.vol, c.ro, c.rdo, c.spread, c.secs)
		for j, got := range [3]float64{r, rd, vol} {
			if math.Abs(got-c.want[j]) > tol {
				t.Errorf("case %d (%+v): output %d = %.9f, want %.9f", i, c, j, got, c.want[j])
			}
		}
	}
}

