// On V2's curve, ten-to-one odds come at about 725 points apart (NASPA's
// curve: 722). On V1's, at 400.
func TestV2Curve(t *testing.T) {
	for _, tc := range []struct {
		p    Params
		want float64
	}{{V1, 400}, {V2, 725}} {
		gap := tc.p.Conversion * math.Log(10)
		if math.Abs(gap-tc.want) > 2 {
			t.Errorf("ten-to-one at %.1f points, want about %.0f", gap, tc.want)
		}
	}
}
