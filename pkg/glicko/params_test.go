func TestV1Unchanged(t *testing.T) {
	checkCases(t, V1, v1Cases, 1e-8)
	// The package-level Rate is V1.
	for _, c := range v1Cases {
		a, b, d := Rate(c.r, c.rd, c.vol, c.ro, c.rdo, c.spread, c.secs)
		e, f, g := V1.Rate(c.r, c.rd, c.vol, c.ro, c.rdo, c.spread, c.secs)
		if a != e || b != f || d != g {
			t.Errorf("Rate and V1.Rate differ on %+v", c)
		}
	}
}

